# Extract a compact, full-precision Fortran fixture for test/test_crop_tails_parity.jl
# from the crop-tails reference dumps (so CI can assert values without the 300 MB
# of dumps). Values are written with `repr` (round-trip exact).
#
#   julia --project=. scripts/validation/crop_parity/extract_crop_tails_fixture.jl [REF_A] [REF_SOY] [OUT]
using NCDatasets

const SD = get(ENV, "SYMFLUENCE_DATA", "/Users/darri/repos/SYMFLUENCE_data")
refA   = length(ARGS) >= 1 ? ARGS[1] : joinpath(SD, "runs", "crop_tails_refA")
refSoy = length(ARGS) >= 2 ? ARGS[2] : joinpath(SD, "runs", "crop_tails_refB_soyfix")
out    = length(ARGS) >= 3 ? ARGS[3] : joinpath(@__DIR__, "..", "..", "..", "test", "fixtures", "crop_tails_fortran_ref.jl")

function load(dir, label, n)
    f = joinpath(dir, "cropdump_$(label)_n$(n).nc")
    isfile(f) || return nothing
    d = Dict{String,Any}()
    NCDataset(f) do ds
        for k in keys(ds)
            v = ds[k]; d[k] = ndims(v) == 0 ? v[] : Array(v[:])
        end
    end
    d
end
steps(dir, label) = sort([parse(Int, m[1]) for m in (match(Regex("^cropdump_$(label)_n(\\d+)\\.nc\$"), f) for f in readdir(dir)) if m !== nothing])

io = IOBuffer()
println(io, "# AUTO-GENERATED by scripts/validation/crop_parity/extract_crop_tails_fixture.jl")
println(io, "# from ctsm5.3.012 crop-tails dumps (docs/CROP_LIFECYCLE_MAP.md §3i-§3k). Do not edit.")
println(io, "# Each entry is a NamedTuple of Fortran inputs + outputs for one routine call.")
println(io)

# ---- 1. grain-fill allocation: contiguous runs of grain-fill steps, chained ----
println(io, "const CT_GRAINFILL = [")
alloc_steps = steps(refA, "after_cropalloc")
d0 = load(refA, "after_cropalloc", first(alloc_steps))
it = d0["ITYPE"]
for itype in (17, 19, 23, 75)
    p = findfirst(==(itype), it)
    # first grain-fill step whose predecessor is also dumped, then 24 consecutive steps
    n0 = nothing
    for n in alloc_steps
        c = load(refA, "after_cropalloc", n)
        if c["CROPLIVE"][p] == 1 && c["HUI"][p] >= c["HUIGRAIN"][p] && (n - 1) in alloc_steps
            pr = load(refA, "after_cropalloc", n - 1)
            if pr["HUI"][p] < pr["HUIGRAIN"][p]          # the 2 -> 3 transition step
                n0 = n; break
            end
        end
    end
    n0 === nothing && continue
  for nstart in (n0, n0 + 240)           # the onset day, and 10 days into grain fill
    ns = [n for n in nstart:(nstart + 23) if n in alloc_steps]
    length(ns) == 24 && (ns[end] - ns[1] == 23) || continue
    ((nstart - 1) in steps(refA, "end_noleach")) || continue
    prev = load(refA, "end_noleach", nstart - 1)
    rows = [load(refA, "after_cropalloc", n) for n in ns]
    g(k) = repr([r[k][p] for r in rows])
    println(io, "  (itype = $itype, nsteps = $(repr(ns)),")
    println(io, "   prior = (aleaf = $(repr(prev["ALEAF"][p])), astem = $(repr(prev["ASTEM"][p])), aleafi = $(repr(prev["ALEAFI"][p])), astemi = $(repr(prev["ASTEMI"][p])), aroot = $(repr(prev["AROOT"][p])), arepr = $(repr(prev["AREPR"][p]))),")
    println(io, "   hui = $(g("HUI")), gddtsoi = $(g("GDDTSOI")), huileaf = $(g("HUILEAF")), huigrain = $(g("HUIGRAIN")),")
    println(io, "   gddmaturity = $(g("GDDMATURITY")), peaklai = $(g("PEAKLAI")),")
    println(io, "   aleaf = $(g("ALEAF")), astem = $(g("ASTEM")), aroot = $(g("AROOT")), arepr = $(g("AREPR")),")
    println(io, "   aleafi = $(g("ALEAFI")), astemi = $(g("ASTEMI"))),")
  end
end
println(io, "]")
println(io)

# ---- 2. grain C flux at grain-fill steps (calc_allometry! + FlexibleCN cn alloc) ----
println(io, "const CT_CNALLOC = [")
cn_steps = steps(refA, "after_cnalloc")
cnt = 0
for n in cn_steps
    d = load(refA, "after_cnalloc", n)
    for p in eachindex(d["ITYPE"])
        (d["ITYPE"][p] >= 17 && d["CROPLIVE"][p] == 1 && d["CPOOL_TO_REPRC"][p] > 0 && d["WTCOL"][p] > 0) || continue
        cnt % 97 == 0 && println(io, "  (n = $n, itype = $(d["ITYPE"][p]), aleaf = $(repr(d["ALEAF"][p])), astem = $(repr(d["ASTEM"][p])), aroot = $(repr(d["AROOT"][p])), arepr = $(repr(d["AREPR"][p])), availc = $(repr(d["AVAILC"][p])), npool = $(repr(d["NPOOL"][p])), c_allometry = $(repr(d["C_ALLOMETRY"][p])), n_allometry = $(repr(d["N_ALLOMETRY"][p])), plant_calloc = $(repr(d["PLANT_CALLOC"][p])), cpool_to_reprc = $(repr(d["CPOOL_TO_REPRC"][p])), cpool_to_reprc_stor = $(repr(d["CPOOL_TO_REPRC_STOR"][p])), cpool_to_leafc = $(repr(d["CPOOL_TO_LEAFC"][p])), cpool_to_livestemc = $(repr(d["CPOOL_TO_LIVESTEMC"][p])), cpool_to_frootc = $(repr(d["CPOOL_TO_FROOTC"][p]))),")
        global cnt += 1
    end
end
println(io, "]")
println(io)

# ---- 3. harvest steps (CNOffsetLitterfall crop branch) ----
println(io, "const CT_HARVEST = [")
for n in steps(refA, "end_noleach")
    post = load(refA, "end_noleach", n)
    haskey(post, "LEAFC_TO_LITTER") || break
    for p in eachindex(post["ITYPE"])
        (post["ITYPE"][p] >= 17 && post["WTCOL"][p] > 0 && post["OFFSET_FLAG"][p] == 1.0 &&
         abs(post["OFFSET_COUNTER"][p] - 3600.0) <= 1800.0) || continue
        pre = load(refA, "after_cnalloc", n)
        f(d, k) = repr(d[k][p])
        println(io, "  (n = $n, itype = $(post["ITYPE"][p]), harvest_count = $(post["HARVEST_COUNT"][p]), offset_counter = $(f(post, "OFFSET_COUNTER")),")
        println(io, "   leafc = $(f(pre, "LEAFC")), frootc = $(f(pre, "FROOTC")), livestemc = $(f(pre, "LIVESTEMC")), reprc = $(f(pre, "REPRC")), cropseedc_deficit = $(f(pre, "CROPSEEDC_DEFICIT")),")
        println(io, "   leafn = $(f(pre, "LEAFN")), frootn = $(f(pre, "FROOTN")), livestemn = $(f(pre, "LIVESTEMN")), reprn = $(f(pre, "REPRN")), cropseedn_deficit = $(f(pre, "CROPSEEDN_DEFICIT")),")
        println(io, "   cpool_to_leafc = $(f(pre, "CPOOL_TO_LEAFC")), cpool_to_livestemc = $(f(pre, "CPOOL_TO_LIVESTEMC")), cpool_to_frootc = $(f(pre, "CPOOL_TO_FROOTC")), cpool_to_reprc = $(f(pre, "CPOOL_TO_REPRC")), npool_to_reprn = $(f(pre, "NPOOL_TO_REPRN")),")
        println(io, "   repr_grainc_to_food = $(f(post, "REPR_GRAINC_TO_FOOD")), repr_grainc_to_seed = $(f(post, "REPR_GRAINC_TO_SEED")), repr_grainn_to_food = $(f(post, "REPR_GRAINN_TO_FOOD")), repr_grainn_to_seed = $(f(post, "REPR_GRAINN_TO_SEED")),")
        println(io, "   leafc_to_litter = $(f(post, "LEAFC_TO_LITTER")), frootc_to_litter = $(f(post, "FROOTC_TO_LITTER")), livestemc_to_litter = $(f(post, "LIVESTEMC_TO_LITTER")), livestemn_to_litter = $(f(post, "LIVESTEMN_TO_LITTER")),")
        println(io, "   leafn_to_litter = $(f(post, "LEAFN_TO_LITTER")), leafn_to_retransn = $(f(post, "LEAFN_TO_RETRANSN")), frootn_to_litter = $(f(post, "FROOTN_TO_LITTER"))),")
    end
end
println(io, "]")
println(io)

# ---- 4. CNSoyfix sweep (one step, soybean patches only) ----
sw = sort(filter(f -> startswith(f, "cropdump_soyfix_sweep_n"), readdir(refSoy)))
NCDataset(joinpath(refSoy, sw[cld(length(sw), 2)])) do ds
    it = Array(ds["ITYPE"][:]); pc = Array(ds["PCOLUMN"][:])
    ps = [p for p in eachindex(it) if it[p] in (23, 24)]
    println(io, "const CT_SOYFIX = (nstep = $(ds["nstep"][]), itype = $(repr(it[ps])), wtcol = $(repr(Array(ds["WTCOL"][:])[ps])),")
    println(io, "   plant_ndemand = $(repr(Array(ds["PLANT_NDEMAND"][:])[ps])), gddmaturity = $(repr(Array(ds["GDDMATURITY"][:])[ps])),")
    cs = pc[ps]
    for (k, dimc) in (("FPG", true), ("SMINN", true), ("WF", true), ("HUI", false), ("SOYFIXN", false), ("SOYFIXN_TO_SMINN", true))
        A = Array(ds[k][:, :])
        M = dimc ? A[cs, :] : A[ps, :]
        println(io, "   $(lowercase(k)) = $(repr(M)),")
    end
    println(io, ")")
end
println(io)

# ---- 5. vernalization calls ----
println(io, "const CT_VERN = [")
for n in steps(refA, "end_noleach")
    pre = load(refA, "after_cnalloc", n); pre === nothing && continue
    post = load(refA, "end_noleach", n)
    for p in eachindex(pre["ITYPE"])
        (pre["ITYPE"][p] in (21, 22) && pre["CROPLIVE"][p] == 1 && pre["T_REF2M_MIN"][p] < 1e30 && pre["VF"][p] != 1.0) || continue
        c = pre["PCOLUMN"][p]
        println(io, "  (n = $n, ymd = $(pre["ymd"]), t_ref2m = $(repr(pre["T_REF2M"][p])), t_ref2m_min = $(repr(pre["T_REF2M_MIN"][p])), t_ref2m_max = $(repr(pre["T_REF2M_MAX"][p])), snow_depth = $(repr(pre["SNOW_DEPTH"][c])), tlai = $(repr(pre["TLAI"][p])),")
        println(io, "   vf0 = $(repr(pre["VF"][p])), cumvd0 = $(repr(pre["CUMVD"][p])), hdidx0 = $(repr(pre["HDIDX"][p])), vf = $(repr(post["VF"][p])), cumvd = $(repr(post["CUMVD"][p])), hdidx = $(repr(post["HDIDX"][p]))),")
